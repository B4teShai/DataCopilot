"""Generate docs/reference/cli.md from the Typer application.

    uv run python scripts/gen_cli_reference.py            # rewrite the page
    uv run python scripts/gen_cli_reference.py --check    # exit 1 when the page is out of date

The page is derived from the option and command definitions (names, defaults, ranges, help text
and docstrings), so it cannot drift from the code; ``tests/docs/test_cli_reference.py`` fails when
the committed page differs from what this script produces.
"""

from __future__ import annotations

import sys
import textwrap
from pathlib import Path
from typing import Any

import typer

from datacopilot.cli.app import app

PAGE = Path(__file__).resolve().parents[1] / "docs" / "reference" / "cli.md"
HEADER = """\
# CLI reference

<!-- Generated by scripts/gen_cli_reference.py from the Typer application. Do not edit by hand:
     run `uv run python scripts/gen_cli_reference.py` and commit the result. -->

Every command reads its configuration from the environment (see
[Trust model](../guide/trust-model.md) and [Install](../guide/install.md)), writes structured JSON
logs to standard error and its result to standard output. Exit code `0` is success, `1` the command
ran and failed (unreadable or invalid input, a gate that matched, a lossy `--strict` conversion),
`2` a usage or configuration error, `130` an interrupt.
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _type_name(param: Any) -> str:
    kind = param.type
    name = str(getattr(kind, "name", "") or type(kind).__name__).upper()
    name = {"TYPERPATH": "PATH", "STR": "TEXT", "STRING": "TEXT", "INT RANGE": "INT"}.get(
        name, name
    )
    low, high = getattr(kind, "min", None), getattr(kind, "max", None)
    if low is not None or high is not None:
        name += f" ({low if low is not None else ''}..{high if high is not None else ''})"
    return name


def _default(param: Any) -> str:
    value = param.default
    if value is None or value is False and not param.is_flag:
        return ""
    if callable(value):
        return ""
    if isinstance(value, bool):
        return "on" if value else "off"
    return f"`{value}`"


def _option_row(param: Any) -> str:
    names = " / ".join(f"`{n}`" for n in [*param.opts, *param.secondary_opts])
    flag = bool(getattr(param, "is_flag", False))
    argument = "" if flag else f"`{_type_name(param)}`"
    required = " (required)" if param.required else ""
    return f"| {names}{required} | {argument} | {_default(param)} | {_cell(param.help or '')} |"


def _paragraphs(doc: str) -> str:
    blocks = [" ".join(block.split()) for block in textwrap.dedent(doc).strip().split("\n\n")]
    return "\n\n".join(textwrap.fill(b, width=100) for b in blocks)


def _usage(name: str, command: Any) -> str:
    arguments = [p for p in command.params if type(p).__name__.endswith("Argument")]
    parts = [f"datacopilot {name}", "[OPTIONS]"]
    parts += [p.name.upper() for p in arguments]
    return " ".join(parts)


def commands_of(group: Any, prefix: str = "") -> dict[str, Any]:
    """Every leaf command of the application, a sub-command named ``group command``."""
    found: dict[str, Any] = {}
    for name, command in group.commands.items():
        if hasattr(command, "commands"):
            found.update(commands_of(command, f"{prefix}{name} "))
        else:
            found[f"{prefix}{name}"] = command
    return found


def render() -> str:
    commands = dict(sorted(commands_of(typer.main.get_command(app)).items()))
    out = [HEADER]
    out.append("## datacopilot\n")
    out.append("`datacopilot [--version] COMMAND [ARGS]...`\n")
    out.append("| Command | Purpose |\n|---|---|")
    for name, command in commands.items():
        first = (command.help or "").strip().splitlines()[0] if command.help else ""
        out.append(f"| [`{name}`](#datacopilot-{name.replace(' ', '-')}) | {_cell(first)} |")
    out.append("\n`--version` prints the version and exits.\n")
    for name, command in commands.items():
        out.append(f"## datacopilot {name}\n")
        out.append(_paragraphs(command.help or "") + "\n")
        out.append(f"```text\n{_usage(name, command)}\n```\n")
        arguments = [p for p in command.params if type(p).__name__.endswith("Argument")]
        options = [p for p in command.params if not type(p).__name__.endswith("Argument")]
        if arguments:
            out.append("| Argument | Description |\n|---|---|")
            for p in arguments:
                out.append(f"| `{p.name.upper()}` | {_cell(p.help or '')} |")
            out.append("")
        if options:
            out.append("| Option | Value | Default | Description |\n|---|---|---|---|")
            out.extend(_option_row(p) for p in options)
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if argv == ["--check"]:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != text:
            print(f"{PAGE} is out of date; run scripts/gen_cli_reference.py", file=sys.stderr)
            return 1
        return 0
    if argv:
        print("usage: gen_cli_reference.py [--check]", file=sys.stderr)
        return 2
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
